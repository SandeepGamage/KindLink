const mongoose = require('mongoose');

const MAX_MESSAGE_LENGTH = 2000;

const messageSchema = new mongoose.Schema(
  {
    conversation: {
      type: mongoose.Schema.Types.ObjectId,
      ref: 'Conversation',
      required: true
    },
    sender: {
      type: mongoose.Schema.Types.ObjectId,
      ref: 'User',
      required: true
    },
    recipient: {
      type: mongoose.Schema.Types.ObjectId,
      ref: 'User',
      required: true
    },
    content: {
      type: String,
      required: [true, 'Message content is required'],
      trim: true,
      maxlength: [MAX_MESSAGE_LENGTH, `Messages cannot exceed ${MAX_MESSAGE_LENGTH} characters`]
    },
    isRead: {
      type: Boolean,
      default: false
    },
    readAt: {
      type: Date,
      default: null
    },
    // Generated by the sending device. Lets the app match its optimistic bubble
    // to the stored message, and makes a retried send idempotent.
    clientId: {
      type: String,
      trim: true,
      default: undefined
    }
  },
  {
    timestamps: true
  }
);

messageSchema.index({ conversation: 1, createdAt: 1 });
messageSchema.index({ recipient: 1, isRead: 1 });
messageSchema.index(
  { sender: 1, clientId: 1 },
  { unique: true, partialFilterExpression: { clientId: { $type: 'string' } } }
);

messageSchema.statics.MAX_LENGTH = MAX_MESSAGE_LENGTH;

module.exports = mongoose.model('Message', messageSchema);
